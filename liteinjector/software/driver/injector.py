import re
import csv
import time

# Hardware/software interface version supported by this driver (see liteinjector.core).
LITEINJECTOR_VERSION = 2

# Fault models (CLI numbering).
FAULT_NONE            = 0
FAULT_BIT_SET         = 1
FAULT_BIT_RESET       = 2
FAULT_BIT_FLIP        = 3
FAULT_BIT_FLIP_RANDOM = 4
FAULT_BIT_VALUE       = 5

# Trigger entry flags (see liteinjector.core).
FLAG_RANDOM = 0

def parse_value(text, width):
    """Parse an integer or a 0b/0x pattern where "x" digits are "don't care".

    Returns (value, mask) where mask selects the bits that are not "don't care".
    """
    mb = re.fullmatch("0b([01x]+)", text)
    mx = re.fullmatch("0x([0-9a-fA-Fx]+)", text)
    m  = mb or mx
    if m is None:
        return int(text, 0), (1 << width) - 1
    digit_bits = 4 if mx is not None else 1
    value = 0
    mask  = 0
    for c in m.group(1):
        value <<= digit_bits
        mask  <<= digit_bits
        if c != "x":
            value |= int(c, 16 if mx is not None else 2)
            mask  |= (1 << digit_bits) - 1
    return value, mask

class LiteInjectorDriver:
    def __init__(self, regs, name, config_csv=None, debug=False):
        self.regs = regs
        self.name = name
        self.config_csv = config_csv
        if self.config_csv is None:
            self.config_csv = name + ".csv"
        self.debug = debug
        self.get_config()
        self.get_layouts()
        self.check_version()
        self.build()
        self.group = 0

        self.trigger_enable.write(0)

    def get_config(self):
        with open(self.config_csv) as f:
            for t, g, n, v in csv.reader(f, delimiter=',', quotechar='#'):
                if t == "config":
                    setattr(self, n, int(v))

    def get_layouts(self):
        self.layouts = {}
        with open(self.config_csv) as f:
            for t, g, n, v in csv.reader(f, delimiter=',', quotechar='#'):
                if t == "signal":
                    self.layouts.setdefault(int(g), []).append((n, int(v)))

    def check_version(self):
        version = getattr(self, "version", 1)
        if version != LITEINJECTOR_VERSION:
            raise RuntimeError(f"{self.config_csv} was generated by a LiteInjector v{version} core, this driver "
                f"supports v{LITEINJECTOR_VERSION}. Rebuild the SoC with the current LiteInjector.")

    def build(self):
        for key, value in self.regs.d.items():
            if self.name == key[:len(self.name)]:
                key = key.replace(self.name + "_", "")
                setattr(self, key, value)
        # Offset ("_o", weight of the LSB) and mask ("_m") of each signal in its group.
        self.fields = {}
        for group, signals in self.layouts.items():
            start = 0
            for name, length in signals:
                self.fields[(group, name)] = (start, length)
                setattr(self, name + "_o", 1 << start)
                setattr(self, name + "_m", ((1 << length) - 1) << start)
                start += length

    # Layout helpers -------------------------------------------------------------------------------

    def get_data_width(self, layout, index):
        return sum(size for _, size in layout[index])

    def field(self, signal_name):
        try:
            return self.fields[(self.group, signal_name)]
        except KeyError:
            raise ValueError(f"Signal {signal_name} is not in group {self.group}.")

    def bits_mask(self, signal_name, locations):
        """Mask of the given bit locations of a signal (all its bits if locations is empty)."""
        start, length = self.field(signal_name)
        if len(locations) == 0:
            return ((1 << length) - 1) << start
        mask = 0
        for location in locations:
            location = int(location)
            if not 0 <= location < length:
                raise ValueError(f"Bit {location} is out of range for {signal_name} ({length} bits).")
            mask |= 1 << (start + location)
        return mask

    def value_mask(self, signal_name, text):
        """Value and mask of a value pattern applied to a signal."""
        start, length = self.field(signal_name)
        value, mask = parse_value(text, length)
        if value >> length:
            raise ValueError(f"Value {text} does not fit in {signal_name} ({length} bits).")
        return value << start, (mask & ((1 << length) - 1)) << start

    # Configuration --------------------------------------------------------------------------------

    def configure_group(self, value):
        self.group = value
        self.mux_value.write(value)

    def clear(self):
        """Flush the pending triggers and reset the counters (also reloads the LFSR seed)."""
        self.trigger_clear.write(1)

    def set_seed(self, seed):
        """Seed of the random bit flip LFSR, applied by the next clear()."""
        self.trigger_seed.write(seed)

    def encode_fault(self, fault, fault_model):
        """Return (fault_and, fault_or, fault_xor, flags) for the given fault list."""
        data_width = self.get_data_width(self.layouts, self.group)
        all_ones   = (1 << data_width) - 1
        fault_and, fault_or, fault_xor, flags = all_ones, 0, 0, 0

        for signal_name, arg, *_ in fault or []:
            if fault_model == FAULT_BIT_SET:
                fault_or  |= self.bits_mask(signal_name, arg)
            elif fault_model == FAULT_BIT_RESET:
                fault_and &= ~self.bits_mask(signal_name, arg) & all_ones
            elif fault_model == FAULT_BIT_FLIP:
                fault_xor |= self.bits_mask(signal_name, arg)
            elif fault_model == FAULT_BIT_FLIP_RANDOM:
                if not getattr(self, "lfsr", 0):
                    raise ValueError("Random bit flip requires a core built with with_lfsr=True.")
                fault_xor |= self.bits_mask(signal_name, arg)
                flags     |= 1 << FLAG_RANDOM
            elif fault_model == FAULT_BIT_VALUE:
                value, mask = self.value_mask(signal_name, arg)
                fault_and &= ~mask & all_ones
                fault_or  |= value & mask
            else:
                raise ValueError(f"Unknown fault model {fault_model}.")

        return fault_and, fault_or, fault_xor, flags

    def add_trigger(self, value=0, mask=0, cond=None, rising_edge=None, falling_edge=None, offset=0, fault=None, fault_model=0, duration=1):
        if self.trigger_mem_full.read():
            raise ValueError("Trigger memory full, too much conditions")

        for k, v in (cond or {}).items():
            v, m = self.value_mask(k, v)
            value |= v
            mask  |= m

        rising_edge_mask = 0
        for signal_name, locations in (rising_edge or {}).items():
            rising_edge_mask |= self.bits_mask(signal_name, locations)

        falling_edge_mask = 0
        for signal_name, locations in (falling_edge or {}).items():
            falling_edge_mask |= self.bits_mask(signal_name, locations)

        if not 0 <= offset <= self.offset_depth:
            raise ValueError(f"Offset {offset} is out of range (0-{self.offset_depth}).")
        if not 0 <= duration <= self.duration_depth:
            raise ValueError(f"Duration {duration} is out of range (0-{self.duration_depth}).")

        fault_and, fault_or, fault_xor, flags = self.encode_fault(fault, fault_model)

        self.trigger_mem_offset.write(offset)
        self.trigger_mem_duration.write(duration)
        self.trigger_mem_mask.write(mask)
        self.trigger_mem_value.write(value)
        self.trigger_mem_r_edge_mask.write(rising_edge_mask)
        self.trigger_mem_f_edge_mask.write(falling_edge_mask)
        self.trigger_mem_fault_and.write(fault_and)
        self.trigger_mem_fault_or.write(fault_or)
        self.trigger_mem_fault_xor.write(fault_xor)
        self.trigger_mem_flags.write(flags)
        self.trigger_mem_write.write(1)

    # Run ------------------------------------------------------------------------------------------

    def run(self):
        if self.debug:
            print("[The injector has been configured]...")
        self.trigger_enable.write(1)

    def stop(self):
        self.trigger_enable.write(0)

    def done(self):
        return self.trigger_done.read()

    def wait_done(self, timeout=None, poll=0.01):
        start = time.time()
        while not self.done():
            if timeout is not None and time.time() - start > timeout:
                return False
            time.sleep(poll)
        return True

    def status(self):
        return {
            "done"           : self.trigger_done.read(),
            "busy"           : self.trigger_busy.read(),
            "hit_count"      : self.trigger_hit_count.read(),
            "fault_count"    : self.trigger_fault_count.read(),
            "hit_timestamp"  : self.trigger_hit_timestamp.read(),
            "capture_before" : self.capture_before.read(),
            "capture_after"  : self.capture_after.read(),
        }
